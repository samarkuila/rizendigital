def _clean_date(s):
    return s.strip().rstrip(',').strip() if s else None


def build_updates():
    """Return update dicts, newest first, with computed display fields."""
    out = []
    for (slug, name, typ, start, end, exact, summary, affected, lesson, src, extra) in _RAW:
        s, e = _d(_clean_date(start)), _d(_clean_date(end))
        out.append({
            'slug': slug,
            'name': name,
            'type': typ,
            'type_label': TYPES[typ]['label'],
            'start': s,
            'end': e,
            'year': s.year,
            'ts': s.strftime('%Y%m%d'),
            'when': _label(s, e, exact),
            'summary': summary,
            'affected': affected,
            'lesson': lesson,
            'todo': TYPES[typ]['todo'],
            'source': (SEJ + src) if src else None,
            'extra': extra,
        })
    out.sort(key=lambda u: u['ts'], reverse=True)
    return out


def year_counts(updates):
    counts = {}
    for u in updates:
        counts[u['year']] = counts.get(u['year'], 0) + 1
    top = max(counts.values())
    return [{'year': y, 'count': counts[y], 'pct': round(counts[y] / top * 100)} for y in sorted(counts)]



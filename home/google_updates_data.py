_MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']


def _d(s):
    if not s:
        return None
    y, m, d = (int(x) for x in s.split('-'))
    return date(y, m, d)


def _label(start, end, exact):
    if not exact:
        if end and end.year == start.year and end.month != start.month:
            return '%s–%s %d' % (_MONTHS[start.month - 1], _MONTHS[end.month - 1], start.year)
        return '%s %d' % (_MONTHS[start.month - 1], start.year)
    s = '%s %d' % (_MONTHS[start.month - 1], start.day)
    if not end:
        return '%s, %d' % (s, start.year)
    if end.year == start.year and end.month == start.month:
        return '%s–%d, %d' % (s, end.day, start.year)
    if end.year == start.year:
        return '%s – %s %d, %d' % (s, _MONTHS[end.month - 1], end.day, start.year)
    return '%s, %d – %s %d, %d' % (s, start.year, _MONTHS[end.month - 1], end.day, end.year)


